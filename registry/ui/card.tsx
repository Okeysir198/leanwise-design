import * as React from "react"

import { cn } from "@/lib/utils"

const Card = React.forwardRef<
  HTMLDivElement,
  React.HTMLAttributes<HTMLDivElement>
>(({ className, ...props }, ref) => (
  <div
    ref={ref}
    // `data-slot` is shadcn's own convention and it is what tests should select
    // on. UserSettingsTab.test.tsx already preferred it and fell back to
    // `.rounded-xl` — so changing the card's radius to the design system's tier
    // broke ten assertions that were, in effect, testing a border-radius. The
    // attribute makes that selector structural instead.
    data-slot="card"
    className={cn(
      "rounded-lg border bg-card text-card-foreground shadow",
      className
    )}
    {...props}
  />
))
Card.displayName = "Card"

