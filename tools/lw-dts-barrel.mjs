#!/usr/bin/env node
/**
 * react.d.ts, generated from react.js.
 *
 * The barrel's TYPES were hand-written beside a barrel whose RUNTIME exports
 * are the real list, and the two drifted the way two homes for one fact always
 * do: four re-exports pointed at a sibling's file (`Container` from `Page`,
 * `Split` from `Grid`, `InputGroup` from `Input`, `SourceList` from
 * `SourceChip`), and THIRTY-ONE components — Icon, DataGrid, both charts,
 * Popover, Menu, Drawer, Combobox, DatePicker and more — had no types at all.
 *
 * The first of those broke `npm run build` outright: rollup-plugin-dts refuses
 * a re-export the target does not declare, so `dts: true` failed and
 * `prepublishOnly` with it. The other thirty-one failed more quietly — a
 * TypeScript consumer importing DataGrid got an error, not a type.
 *
 * react.js is the authority on WHAT is exported; each component's own .d.ts is
 * the authority on its TYPES. This just joins them, so the barrel cannot drift
 * from either again. Same contract as tokens.json: generated, committed, and
 * staleness-checked in CI.
 *
 *   node lw-dts-barrel.mjs            # write react.d.ts
 *   node lw-dts-barrel.mjs --check    # fail if the committed file is stale
 */
import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const OUT = join(ROOT, "react.d.ts");
const checkOnly = process.argv.includes("--check");

const js = readFileSync(join(ROOT, "react.js"), "utf8");

/** Names a component's .d.ts actually declares. */
function declared(specifier) {
  const rel = specifier.replace(/^\.\//, "").replace(/\.jsx$/, "") + ".d.ts";
  const path = join(ROOT, rel);
  if (!existsSync(path)) return null;
  const src = readFileSync(path, "utf8");
  const out = new Set();
  for (const m of src.matchAll(/export\s+(?:declare\s+)?(?:function|const|interface|type|class)\s+(\w+)/g)) out.add(m[1]);
  for (const m of src.matchAll(/export\s*\{([^}]*)\}/g)) {
    for (const n of m[1].split(",").map((s) => s.trim().replace(/^type\s+/, "")).filter(Boolean)) out.add(n);
  }
  return out;
}

const groups = [];
const problems = [];
for (const m of js.matchAll(/export\s*\{([^}]*)\}\s*from\s*"([^"]+)"/g)) {
  const names = m[1].split(",").map((s) => s.trim()).filter(Boolean);
  const spec = m[2];
  const have = declared(spec);
  if (have === null) {
    problems.push(`no .d.ts beside ${spec} (for ${names.join(", ")})`);
    continue;
  }
  for (const n of names) if (!have.has(n)) problems.push(`${spec.replace(/\.jsx$/, "")}.d.ts does not declare ${n}`);
  // Re-export the Props types alongside their component: a consumer typing a
  // wrapper needs ButtonProps, and it is free to carry here.
  const props = names.map((n) => n + "Props").filter((p) => have.has(p));
  groups.push({ names, props, path: spec.replace(/\.jsx$/, "") });
}

if (problems.length) {
  console.error("lw-dts-barrel: " + problems.length + " export(s) in react.js have no matching declaration:");
  for (const p of problems) console.error("  · " + p);
  console.error("  Add the declaration to the component's .d.ts — do not drop it from react.js.");
  process.exit(1);
}

const body = groups
  .map((g) => {
    const value = `export { ${g.names.join(", ")} } from "${g.path}";`;
    return g.props.length ? value + `\nexport type { ${g.props.join(", ")} } from "${g.path}";` : value;
  })
  .join("\n");

const want = `/** Ambient types for the React barrel. Each component's own .d.ts is the
 *  source of truth; this file only re-exports them.
 *
 *  GENERATED by tools/lw-dts-barrel.mjs from react.js — do not
 *  hand-edit. Add the export to react.js and the declaration to the
 *  component's .d.ts, then run \`npm run dts\`.
 */
${body}
`;


/* ---------------------------------------------------------------------------
 * IconName — generated from Icon.jsx's ICONS table.
 *
 * It was hand-maintained and had drifted to 46 of the 78 real glyphs, so passing
 * a name the component renders perfectly well was a type error. This generator
 * never looked at it and there was no tsconfig, so nothing could have said so.
 * ------------------------------------------------------------------------- */

const ICON_DTS = join(ROOT, "components", "primitives", "Icon.d.ts");
const iconSrc = readFileSync(join(ROOT, "components", "primitives", "Icon.jsx"), "utf8");
const iconBody = iconSrc.slice(iconSrc.indexOf("const ICONS"), iconSrc.indexOf("export function Icon"));
const glyphs = [...iconBody.matchAll(/^\s+"?([a-zA-Z0-9-]+)"?\s*:\s*\[/gm)].map((m) => m[1]);
if (glyphs.length < 20) {
  console.error("lw-dts-barrel: only found " + glyphs.length + " glyphs in Icon.jsx — the ICONS table shape changed.");
  console.error("  Refusing to write a union that would silently reject valid names.");
  process.exit(1);
}
const iconLines = [];
for (let i = 0; i < glyphs.length; i += 6) {
  iconLines.push("  | " + glyphs.slice(i, i + 6).map((g) => `"${g}"`).join(" | "));
}
const iconUnion = "export type IconName =\n" + iconLines.join("\n") + ";";
const iconHave = readFileSync(ICON_DTS, "utf8");
const iconWant = iconHave.replace(/export type IconName =[\s\S]*?;/, iconUnion);

if (checkOnly) {
  if (iconHave !== iconWant) {
    console.error("lw-dts-barrel: IconName is stale — Icon.jsx has " + glyphs.length + " glyphs and the union does not match.");
    console.error("  A missing member makes a name the component RENDERS a type error. Run `npm run dts`.");
    process.exit(1);
  }
} else if (iconHave !== iconWant) {
  writeFileSync(ICON_DTS, iconWant);
  console.log("lw-dts-barrel: regenerated IconName — " + glyphs.length + " glyphs.");
}

if (checkOnly) {
  const have = existsSync(OUT) ? readFileSync(OUT, "utf8") : null;
  if (have !== want) {
    console.error("lw-dts-barrel: react.d.ts is stale — react.js has moved since it was generated.");
    console.error("  Run `npm run dts` and commit the result.");
    process.exit(1);
  }
  console.log("lw-dts-barrel: OK — react.d.ts covers all " + groups.reduce((n, g) => n + g.names.length, 0) + " barrel exports.");
  process.exit(0);
}
writeFileSync(OUT, want);
console.log("lw-dts-barrel: wrote react.d.ts — " + groups.reduce((n, g) => n + g.names.length, 0) + " exports, " + groups.reduce((n, g) => n + g.props.length, 0) + " prop types.");
